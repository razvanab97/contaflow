const assert = require('node:assert/strict')
const { PDFDocument } = require('pdf-lib')
async function main() {
  const { mergeOfferFiles } = await import('../lib/achizitii-offer-files.ts')
  const { dosarAchizitie } = await import('../lib/achizitii-procedura.ts')
  const png = new Uint8Array(Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jRZkAAAAASUVORK5CYII=', 'base64'))
  const source = await PDFDocument.create(); source.addPage([300, 400]); source.addPage([400, 300])
  const bytes = await mergeOfferFiles([{ type: 'image/png', bytes: png }, { type: 'application/pdf', bytes: await source.save() }, { type: 'image/png', bytes: png }])
  const result = await PDFDocument.load(bytes)
  assert.equal(result.getPageCount(), 4)
  assert.equal(result.getPage(1).getWidth(), 300)
  assert.equal(result.getPage(2).getWidth(), 400)
  await assert.rejects(()=>mergeOfferFiles([]))
  await assert.rejects(()=>mergeOfferFiles([{type:'image/webp',bytes:png}]))
  await assert.rejects(()=>mergeOfferFiles([{type:'image/png',bytes:new Uint8Array(4*1024*1024+1)}]))
  const doc = supplier => ({ fisier_nume: `Oferta [furnizor=${supplier}] - Furnizor.pdf`, tip_document: 'oferta', fisier_tip: 'application/pdf' })
  const offers = docs => dosarAchizitie(docs).find(item=>item.cheie==='oferte')
  assert.equal(offers([doc('a'),doc('a'),doc('a')]).ok, false)
  assert.match(offers([doc('a'),doc('a')]).detaliu,/1 din 3/)
  assert.equal(offers([doc('a'),doc('b'),doc('c')]).ok,true)
  assert.equal(offers([{fisier_nume:'Cerere de oferta Anexa 2.pdf',tip_document:'oferta'}]).ok,false)
  assert.match(offers([{fisier_nume:'Oferta veche.pdf',tip_document:'oferta'}]).detaliu,/vechi negrupate/)
  console.log('OK: poze + PDF în ordine, limite, oferte grupate per furnizor, compatibilitate fișiere vechi.')
}
main().catch(error => { console.error(error); process.exitCode = 1 })
