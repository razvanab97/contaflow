const fs=require('node:fs'),assert=require('node:assert/strict'),path=require('node:path'),os=require('node:os')
const root=path.resolve(__dirname,'..'),out=fs.mkdtempSync(path.join(os.tmpdir(),'contaflow-impozite-'))
const swc=require(root+'/node_modules/next/dist/build/swc')
;(async()=>{
  await swc.loadBindings()
  const src=fs.readFileSync(root+'/lib/impozite-mail.ts','utf8')
  const result=await swc.transform(src,{filename:'impozite-mail.ts',jsc:{parser:{syntax:'typescript'},target:'es2022'},module:{type:'commonjs'}})
  fs.writeFileSync(out+'/impozite-mail.cjs',result.code)
  const m=require(out+'/impozite-mail.cjs')
  assert.equal(m.parseTaxAmount('1.833 lei'),1833)
  assert.equal(m.parseTaxAmount('1.833,50'),1833.5)
  assert.equal(m.parseTaxAmount('820'),820)
  assert.equal(m.validIban('RO49 AAAA 1B31 0075 9384 0000'),true)
  assert.equal(m.validIban('RO49 AAAA 1B31 0075 9384 0001'),false)
  const email='Pentru ABXHOMES SRL e de platit pentru luna AUGUST 2026:\n1. pe CUI 51540013\n- 820 lei BS in contul RO95TREZ4065503XXXOOO0OGX\n2. pe CIF 51842895\n- 1833 lei TVA in contul RO41TREZ40620A100101XTVA'
  const draft=m.parseTaxEmail(email)
  assert.equal(draft.company,'ABXHOMES SRL')
  assert.equal(draft.period,'AUGUST 2026')
  assert.equal(draft.payments.length,2)
  assert.equal(m.parseTaxEmail(email+'\nTotal 2653 lei').payments.length,2)
  assert.deepEqual(draft.payments.map(p=>[p.label,p.amount,p.fiscalId]),[['BS',820,'51540013'],['TVA',1833,'51842895']])
  assert.equal(draft.payments[0].iban,'RO95TREZ4065503XXXOOO0OGX')
  assert.equal(draft.payments[1].iban,'RO41TREZ40620A100101XTVA')
  assert.equal(m.parseTaxEmail('1. pe CIF 12345678\n- 50 lei TVA').payments.length,1)
  assert.equal(m.parseTaxEmail('pe CUI RO 12345678\n- 50 lei TVA in contul RO49AAAA1B31007593840000').payments[0].fiscalId,'RO12345678')
  assert.equal(draft.payments[1].description,'TVA — luna AUGUST 2026')
  assert(m.paymentIssues(m.parseTaxEmail('1. pe CIF 12345678\n- 50 lei TVA').payments[0]).some(x=>x.includes('IBAN')))
  const textile=m.parseTaxEmail('AB TEXTILE SRL - OBLIGATII DE PLATA BUGET AUGUST 2026\nLa AB TEXTILE SRL ( CUI 12345678) este de plata la buget pentru luna AUGUST 2026:\n- 100 lei BAS+BS in contul RO49AAAA1B31007593840000 (salarii)\n- 20 lei CAM in contul RO49AAAA1B31007593840000')
  assert.equal(textile.company,'AB TEXTILE SRL')
  assert.equal(textile.period,'AUGUST 2026')
  assert.equal(textile.subjectPeriod,'AUGUST 2026')
  assert.deepEqual(textile.payments.map(p=>[p.label,p.amount,p.fiscalId]),[['BAS+BS',100,'12345678'],['CAM',20,'12345678']])
  assert.equal(textile.payments[0].description,'BAS+BS (salarii) — luna AUGUST 2026')
  assert.equal(textile.payments.reduce((sum,p)=>sum+p.amount,0),120)
  assert.equal(m.sameTaxCompany(textile.company,'AB Textile'),true)
  assert.deepEqual(m.taxPeriodReview(textile,'2026-09'),[])
  const invest=m.parseTaxEmail('AB HOMES INVEST SRL - OBLIGATII BUGET AUGUST 2026\nPentru ABHOMES INVEST SRL ( CUI 12345678) e de platit pentru luna AUGUST 2025:\n- 1.561 lei BAS in contul RO49AAAA1B31007593840000\n- 9 lei CAM in contul RO49AAAA1B31007593840000\n- 61 lei TVA in contul RO49AAAA1B31007593840000')
  assert.equal(invest.company,'ABHOMES INVEST SRL')
  assert.deepEqual(invest.payments.map(p=>[p.label,p.amount,p.fiscalId]),[['BAS',1561,'12345678'],['CAM',9,'12345678'],['TVA',61,'12345678']])
  assert.equal(invest.payments.reduce((sum,p)=>sum+p.amount,0),1631)
  assert.equal(m.sameTaxCompany(invest.company,'AB Homes Invest'),true)
  assert.equal(invest.subjectPeriod,'AUGUST 2026')
  assert.equal(invest.period,'AUGUST 2025')
  assert.equal(m.taxPeriodReview(invest,'2026-09').length,2)
  assert.equal(m.normalizeTaxDraft(invest).subjectPeriod,'AUGUST 2026')
  assert.equal(m.expectedTaxPeriod('2026-09'),'AUGUST 2026')
  assert.equal(m.expectedTaxPeriod('2026-09-01'),'AUGUST 2026')
  assert.equal(m.taxPeriodReview(invest,'2026-09-01').length,2)
  const textileOcr=m.parseTaxEmail('AB TEXTILE SRL - OBLIGATII DE PLATA BUGET AUGUST 2026\nLa AB TEXTILE SRL ( CUI 12345678) este de plata la buget pentru luna AUGUST 2026:\n- 100 lei BAS-+BS in contul RO00TEST4095503XXXXX0XXX (salarii)\n- 20 lei CAM in contul RO00TEST40920A470300XXXX')
  assert.equal(textileOcr.payments[0].label,'BAS+BS')
  const investOcr=m.parseTaxEmail('AB HOMES INVEST SRL - OBLIGATII BUGET AUGUST 2026\nPentru ABHOMES INVEST SRL ( CUI 12345678) e de platit pentru luna AUGUST 2025:\n- 1.561 lei BAS in contul RO00TEST4095503XXXXXOOXX\n- 9 lei CAM in contul RO00TEST40920A470300XXXX\n- 61 lei TVA in contul ROLOTEST40920A100101XTVA')
  assert.equal(investOcr.payments.length,3)
  assert(investOcr.payments.every(p=>p.iban.startsWith('RO')))
  assert.equal(investOcr.payments[2].iban,'RO10TEST40920A100101XTVA')
  assert(investOcr.warnings.some(x=>x.includes('corectate din OCR')))
  assert(m.paymentIssues(investOcr.payments[2]).some(x=>x.includes('IBAN invalid')))
  const panelSource=fs.readFileSync(root+'/app/(app)/[firma]/[luna]/modules/TaxMailPanel.tsx','utf8').replace("from '@/lib/impozite-mail'","from './impozite-mail.cjs'")
  const panelCode=await swc.transform(panelSource,{filename:'TaxMailPanel.tsx',jsc:{parser:{syntax:'typescript',tsx:true},target:'es2022',transform:{react:{runtime:'automatic'}}},module:{type:'commonjs'}})
  const panel={exports:{}}
  new Function('require','module','exports',panelCode.code)((name)=>name==='./impozite-mail.cjs'?m:require(name),panel,panel.exports)
  const React=require('react'),{renderToStaticMarkup}=require('react-dom/server')
  const savedHtml=renderToStaticMarkup(React.createElement(panel.exports.PaymentSummary,{payment:{id:'test',sourceId:'test',label:'TVA',amount:61,iban:'RO10TEST40920A100101XTVA',fiscalId:'12345678',recipient:'',description:'TVA',due:null,paid:false},onCopy:()=>{},onEdit:()=>{},onPaid:()=>{},busy:false}))
  assert.doesNotMatch(savedHtml,/<input\b/)
  for(const label of ['IBAN','Sumă','CUI/CIF','Detalii'])assert(savedHtml.includes('aria-label="Copiază '+label+'"'))
  assert(savedHtml.includes('Editează'))
  assert(savedHtml.includes('RO10TEST40920A100101XTVA'))
  if(process.argv.includes('--storage')){
    process.loadEnvFile(root+'/.env.local')
    const storeSource=fs.readFileSync(root+'/lib/impozite-mail-store.ts','utf8')
      .replace("import { getServiceSupabase } from '@/lib/supabase/server'","const {getServiceSupabase}=require('./sb.cjs')")
      .replace("from '@/lib/impozite-mail'","from './impozite-mail.cjs'")
    const compiled=await swc.transform(storeSource,{filename:'impozite-mail-store.ts',jsc:{parser:{syntax:'typescript'},target:'es2022'},module:{type:'commonjs'}})
    fs.writeFileSync(out+'/impozite-mail-store.cjs',compiled.code)
    fs.writeFileSync(out+'/sb.cjs',"const {createClient}=require('"+root+"/node_modules/@supabase/supabase-js');let client;exports.getServiceSupabase=()=>client??=createClient(process.env.NEXT_PUBLIC_SUPABASE_URL,process.env.SUPABASE_SERVICE_ROLE_KEY);")
    const store=require(out+'/impozite-mail-store.cjs'),sb=require(out+'/sb.cjs').getServiceSupabase()
    const prefix='test-impozite-mail/'+require('node:crypto').randomUUID()
    try{
      assert.equal((await store.readTaxMail(prefix)).version,0)
      const first=await store.writeTaxMail(prefix,m.emptyTaxMailState(),0)
      assert.equal(first.version,1)
      const results=await Promise.allSettled([store.writeTaxMail(prefix,first,1),store.writeTaxMail(prefix,first,1)])
      assert.equal(results.filter(x=>x.status==='fulfilled').length,1)
      assert.equal(results.filter(x=>x.status==='rejected'&&x.reason.status===409).length,1)
      assert.equal((await store.readTaxMail(prefix)).version,2)
      console.log('PASS: stocare reală, recitire și prevenirea suprascrierii simultane.')
    }finally{
      const {data}=await sb.storage.from('documente').list(prefix+'/revisions')
      if(data?.length){const {error}=await sb.storage.from('documente').remove(data.map(x=>prefix+'/revisions/'+x.name));if(error)throw error}
    }
  }
  console.log('PASS: sume, IBAN-uri din toate cele trei plăți, corectare OCR semnalată și fișe salvate cu copiere/editare.')
})().catch(e=>{console.error(e);process.exit(1)})
